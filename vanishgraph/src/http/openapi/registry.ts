/**
 * Webhook ingress routes (SPEC-003 §6).
 *
 * Kept OUT of ROUTES on purpose: these are authenticated by signature and a capability
 * token, not by a bearer scope. SPEC-003 §3.3 states `vg.webhooks.ingest` is deliberately
 * absent from the scope vocabulary so no token can carry a scope that would let a caller
 * forge ingress. A contract test asserts no scope in ROUTES is a webhook scope.
 */
export const WEBHOOK_ROUTES = [
  { id: '6.1', method: 'POST', path: '/v1/webhooks/controller-callbacks/{controllerCallbackToken}' },
  { id: '6.2', method: 'POST', path: '/v1/webhooks/provider-callbacks/{providerKeyId}' },
  { id: '6.3', method: 'POST', path: '/v1/webhooks/mail-tracking/{mailProviderKeyId}' },
] as const;

/** Look up a route by method and path template. */
export function findRoute(method: string, path: string): RouteDefinition | undefined {
  return ROUTES.find((route) => route.method === method && route.path === path);
}

/** The routes that must carry an `Idempotency-Key` (SPEC-003 §4.1). */
export const EFFECT_BEARING_ROUTES: readonly RouteDefinition[] = ROUTES.filter(
  (route) => route.idempotency === 'required',
);
