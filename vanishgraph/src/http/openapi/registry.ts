/**
 * The `/v1` route registry — the single source of truth for the route catalogue.
 *
 * SPEC-003 §5 is the contract; this file is its machine-readable form. Two properties make it
 * worth having rather than documenting routes in prose:
 *
 *  1. `src/http/routes/**` registers AGAINST this registry, and a contract test asserts the
 *     registered set equals this set exactly. A route implemented but unregistered is a
 *     defect, and so is an entry with no implementation — neither can hide.
 *  2. It is generated from SPEC-003 by extraction and then reviewed. Hand-transcribing 78
 *     routes is how a scope gets silently dropped from one of them.
 *
 * SCOPE VOCABULARY IS CLOSED (SPEC-003 §3.3). Every `scopes` entry below appears in that
 * table, and the contract test asserts closure, so a typo such as `vg.subject.read` fails
 * the build rather than silently denying every request that needs it.
 *
 * `truthState` appears nowhere in this file and in no request schema: SM-6 makes a truth
 * state the output of a guarded command, never an input.
 *
 * MEASURED: SPEC-003 §5 has 78 routes across 17 groups, not 79. See the EP-004 §12
 * Surprises entry for the three-way count and for the §5.9.1 source defect that makes that
 * route's Scope line unparseable by a line-anchored extractor.
 */

